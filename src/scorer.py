"""Общий интерфейс скоринга пар «запрос — объявление»."""

from abc import ABC, abstractmethod
from typing import Self

import numpy as np
import pandas as pd
from numpy.typing import NDArray
from sklearn.base import BaseEstimator


class PairScorer(BaseEstimator, ABC):
    """Базовый класс одиночных скореров и их ансамблей.

    X — таблица пар: одна строка на пару, с query_id, item_id и полями,
    необходимыми конкретной реализации. Реализация документирует свою схему
    и поведение для пустых текстов и неизвестных ID.

    Параметры задаются в __init__, обученное состояние — в атрибутах
    с суффиксом _. Метрики вычисляются отдельно от скорера.
    """

    @abstractmethod
    def fit(
        self,
        X: pd.DataFrame,
        y: NDArray[np.number] | None = None,
        *,
        corpus: pd.DataFrame | None = None,
    ) -> Self:
        """Подготовить модель и вернуть self, заменив предыдущее состояние.

        y, если задан, содержит одну метку на строку X в том же порядке.
        Скореры без учителя могут игнорировать y.
        corpus — отдельная таблица уникальных объявлений для вычисления
        корпусных статистик; её обязательность определяет реализация.
        Входные данные не изменяются.
        """
        ...

    @abstractmethod
    def predict(self, X: pd.DataFrame) -> NDArray[np.floating]:
        """Вернуть конечные scores формы (len(X),) в порядке строк X.

        Чем выше score, тем релевантнее объявление. Сравнимость обязательна
        внутри запроса; диапазон значений не ограничен. Строки не удаляются,
        для пустой таблицы со схемой возвращается пустой одномерный массив.
        Результат не зависит от размера батча и соседних пар. Метод
        не обучает модель и не изменяет входные данные.
        """
        ...
